<h2 id="privacy">Αιτήματα πελατών για τα προσωπικά τους δεδομένα</h2>
<p>Το COD Guard συνεργάζεται με τα τυπικά εργαλεία απορρήτου του WordPress, οπότε διαχειρίζεστε τα δεδομένα του όπως και τα υπόλοιπα δεδομένα πελατών. Αποθηκεύει τα στοιχεία των πελατών ως κρυπτογραφικά αποτυπώματα και όχι ως αναγνώσιμο κείμενο, και δεν τα μοιράζεται με τρίτους. Τα εργαλεία αυτά συνήθως απαιτούν λογαριασμό Διαχειριστή.</p>
<table class="drpm-guide__table">
    <thead><tr><th scope="col">Αίτημα</th><th scope="col">Τι κάνετε</th><th scope="col">Αποτέλεσμα</th></tr></thead>
    <tbody>
        <tr><td>«Τι στοιχεία έχετε για εμένα;»</td><td><strong>Εργαλεία → Εξαγωγή προσωπικών δεδομένων</strong></td><td>Περιλαμβάνει τις παραγγελίες που ελέγχθηκαν, αν υπάρχει περιορισμός και τυχόν εξαίρεση</td></tr>
        <tr><td>«Διαγράψτε τα δεδομένα μου»</td><td><strong>Εργαλεία → Διαγραφή προσωπικών δεδομένων</strong></td><td>Εξαρτάται από την παρακάτω ρύθμιση</td></tr>
    </tbody>
</table>
<p>Το αν η διαγραφή αφαιρεί τα δεδομένα του COD Guard εξαρτάται από τη ρύθμιση <strong>Αφαίρεση προσωπικών δεδομένων από τις παραγγελίες κατόπιν αιτήματος</strong>, στο <strong>WooCommerce → Ρυθμίσεις → Λογαριασμοί &amp; Απόρρητο</strong>. Αν είναι ενεργή, αφαιρούνται το ιστορικό αρνήσεων και οι εξαιρέσεις του πελάτη. Αν όχι, διατηρούνται για την πρόληψη απάτης και το αίτημα το αναφέρει.</p>
<p>Προσθέστε το προτεινόμενο κείμενο στην πολιτική απορρήτου σας. Θα το βρείτε στο <strong>Ρυθμίσεις → Απόρρητο → Οδηγός πολιτικής</strong>. Προσαρμόστε το στο κατάστημά σας και ελέγξτε το με τον νομικό σας σύμβουλο, καθώς δεν αποτελεί νομική συμβουλή.</p>

<h2 id="updating">Ενημέρωση του πρόσθετου</h2>
<p>Οι ενημερώσεις δεν εγκαθίστανται από μόνες τους: κάποιος με λογαριασμό Διαχειριστή εγκρίνει την καθεμία, εκτός αν έχει ενεργοποιήσει τις αυτόματες ενημερώσεις για το πρόσθετο. Όταν κυκλοφορεί νέα έκδοση, εμφανίζεται στα <strong>Πρόσθετα</strong> όπως σε κάθε άλλο πρόσθετο.</p>
<ol>
    <li>Πάρτε αντίγραφο ασφαλείας της ιστοσελίδας σας.</li>
    <li>Πηγαίνετε στα <strong>Πρόσθετα</strong> και βρείτε το <strong>COD Guard για WooCommerce</strong>.</li>
    <li>Πατήστε <strong>Προβολή λεπτομερειών</strong> για να δείτε τι άλλαξε.</li>
    <li>Πατήστε <strong>Ενημέρωση τώρα</strong>.</li>
</ol>
<p>Το WordPress ελέγχει για ενημερώσεις περίπου δύο φορές την ημέρα. Για άμεσο έλεγχο, πηγαίνετε στο <strong>Πίνακας Ελέγχου → Ενημερώσεις → Επανέλεγχος</strong>.</p>
<p>Οι ρυθμίσεις και το ιστορικό αρνήσεων παραμένουν κατά την ενημέρωση.</p>
<p>Προσέξτε αν χρειαστεί ποτέ να διαγράψετε το πρόσθετο. Αν είναι επιλεγμένη η <strong>Απεγκατάσταση</strong> στο <strong>Ρυθμίσεις → Για προχωρημένους</strong>, η διαγραφή σβήνει τα δεδομένα του COD Guard και μεταφέρει τις παραγγελίες με άρνηση στην κατάσταση Ακυρωμένη. Αφήστε την ανεπίλεκτη, εκτός αν αφαιρείτε οριστικά το COD Guard.</p>

<h2 id="questions">Συχνές ερωτήσεις</h2>
<h3>Ένας πελάτης ρωτά γιατί δεν βλέπει πια την αντικαταβολή. Τι να του πω;</h3>
<p>Ανοίξτε μια παραγγελία του και δείτε το πλαίσιο COD Guard. Εμφανίζει τις παραγγελίες με άρνηση που προκάλεσαν τον περιορισμό, ώστε να τις ελέγξετε μαζί. Αν ο περιορισμός δεν είναι δίκαιος, προσθέστε τον στο <strong>Πάντα αξιόπιστος</strong>.</p>
<h3>Ένας πελάτης που περίμενα να έχει περιορισμό βλέπει ακόμη την αντικαταβολή. Γιατί;</h3>
<p>Ελέγξτε με τη σειρά:</p>
<ol>
    <li>Η <strong>Προστασία ταμείου</strong> είναι επιλεγμένη και ο τρόπος πληρωμής είναι επιλεγμένος στο <strong>Απόκρυψη αυτών των τρόπων πληρωμής</strong>.</li>
    <li>Οι αρνήσεις του έχουν σημειωθεί ως <strong>Άρνηση παραλαβής</strong> και βρίσκονται μέσα στην περίοδο ελέγχου.</li>
    <li>Έχει φτάσει τον κανόνα περιορισμού σας.</li>
    <li>Χρησιμοποίησε email ή τηλέφωνο που αντιστοιχίζετε. Τα νέα στοιχεία δεν μπορούν να συνδεθούν με τις παλιές του παραγγελίες.</li>
    <li>Δεν βρίσκεται στο <strong>Πάντα αξιόπιστος</strong>.</li>
    <li>Υπάρχει διαθέσιμος άλλος τρόπος πληρωμής. Αν όχι, δεν κρύβεται τίποτα.</li>
</ol>
<h3>Μπορεί ένας πελάτης με περιορισμό να παραγγείλει;</h3>
<p>Ναι. Απλώς δεν μπορεί να χρησιμοποιήσει τους κρυμμένους τρόπους πληρωμής. Το COD Guard δεν μπλοκάρει ποτέ την ίδια την παραγγελία.</p>
<h3>Μπορεί κάποιος να το παρακάμψει με νέο email;</h3>
<p>Όχι, αν αντιστοιχίζετε και το τηλέφωνο και δώσει το ίδιο. Όποιος χρησιμοποιήσει εντελώς νέο email και τηλέφωνο δεν θα αναγνωριστεί.</p>
<h3>Λήγει ποτέ ένας περιορισμός;</h3>
<p>Ναι, αυτόματα, μόλις αρκετές αρνήσεις βγουν εκτός της περιόδου ελέγχου. Με περίοδο 0 (όλο το διάστημα), λήγει μόνο αν ορίσετε εξαίρεση. Μπορείτε να τον αναιρέσετε οποιαδήποτε στιγμή με το <strong>Πάντα αξιόπιστος</strong>.</p>
<h3>Να σημειώσω άρνηση αν ο courier δεν βρήκε τη διεύθυνση;</h3>
<p>Χρησιμοποιήστε την <strong>Άρνηση παραλαβής</strong> μόνο όταν ο πελάτης πραγματικά αρνήθηκε το δέμα. Για αποτυχημένες παραδόσεις χωρίς δική του ευθύνη, επιλέξτε <strong>Ακυρωμένη</strong>, ώστε να μη μετρήσουν εις βάρος του.</p>
<h3>Οι αριθμοί φαίνονται λάθος. Τι μπορώ να κάνω;</h3>
<p>Πηγαίνετε στο <strong>Ρυθμίσεις → Για προχωρημένους</strong> και πατήστε <strong>Ανακατασκευή ευρετηρίου</strong>. Εκτελείται στο παρασκήνιο και ο πίνακας ελέγχου δείχνει ειδοποίηση μέχρι να ολοκληρωθεί. Οι παραγγελίες σας δεν αλλάζουν.</p>
<h3>Ποιοι μπορούν να χρησιμοποιήσουν το COD Guard;</h3>
<p>Όποιος μπορεί να διαχειριστεί το WooCommerce, δηλαδή οι ρόλοι Διαχειριστής Καταστήματος (Shop Manager) και Διαχειριστής.</p>
