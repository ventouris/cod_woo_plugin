<h2 id="what-it-does">Τι κάνει το COD Guard</h2>
<p>Το COD Guard εμποδίζει τους πελάτες που αρνούνται επανειλημμένα να παραλάβουν δέματα να ξαναπληρώσουν με αντικαταβολή. Μπορούν και πάλι να παραγγείλουν, με οποιονδήποτε άλλο τρόπο πληρωμής προσφέρετε.</p>
<p>Λειτουργεί σε τρία βήματα:</p>
<ol>
    <li>Όταν ένα δέμα επιστρέφει, σημειώνετε την παραγγελία ως <strong>Άρνηση παραλαβής</strong>.</li>
    <li>Το COD Guard καταγράφει την άρνηση και τη συνδέει με το email, το τηλέφωνο, τις διευθύνσεις και το όνομα του πελάτη, ανάλογα με το τι έχετε επιλέξει για αντιστοίχιση.</li>
    <li>Όταν ο πελάτης φτάσει ξανά στο ταμείο και έχει ξεπεράσει το όριό σας, οι τρόποι πληρωμής που επιλέξατε κρύβονται.</li>
</ol>
<p>Θα το βρείτε στο <strong>WooCommerce → COD Guard</strong>, στις καρτέλες <strong>Πίνακας ελέγχου</strong> και <strong>Ρυθμίσεις</strong>. Οι εικόνες αυτού του οδηγού προέρχονται από δοκιμαστικό κατάστημα.</p>

<h2 id="getting-started">Πρώτα βήματα</h2>
<p>Η ρύθμιση διαρκεί περίπου πέντε λεπτά και οι παρακάτω τιμές ταιριάζουν στα περισσότερα καταστήματα. Πηγαίνετε στο <strong>WooCommerce → COD Guard → Ρυθμίσεις</strong>.</p>

<h3>1. Επιλέξτε πώς αναγνωρίζονται οι πελάτες</h3>
<p>Βεβαιωθείτε ότι η <strong>Προστασία ταμείου</strong> είναι επιλεγμένη και, στο <strong>Αντιστοίχιση με</strong>, επιλέξτε <strong>Email</strong> και <strong>Αριθμός τηλεφώνου</strong>. Μια παλιά παραγγελία μετράει αν ταιριάζει σε οποιοδήποτε επιλεγμένο στοιχείο, οπότε όποιος χρησιμοποιήσει νέο email με το ίδιο τηλέφωνο αναγνωρίζεται κανονικά.</p>
<p>Οι διευθύνσεις και τα ονόματα μπορεί να ταιριάξουν και με άλλα άτομα, όπως συγκατοίκους ή συνωνυμίες. Χρησιμοποιήστε τα μόνο μαζί με email ή τηλέφωνο.</p>
<?php $image('settings-recognise', 'Ρυθμίσεις «Γενικά» και «Αντιστοίχιση με», με επιλεγμένα το email και τον αριθμό τηλεφώνου'); ?>

