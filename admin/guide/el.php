    <li><strong>Περίοδος ελέγχου:</strong> η προεπιλογή είναι 24 μήνες. Οι παλαιότερες αρνήσεις παύουν να μετρούν, ώστε οι πελάτες να ξεκινούν από την αρχή. Το 0 σημαίνει όλο το διάστημα.</li>
