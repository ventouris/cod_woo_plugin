<p>Μπορείτε επίσης να αλλάξετε το <strong>Μήνυμα στο ταμείο</strong> που βλέπουν οι πελάτες με περιορισμό ή να το αφήσετε κενό, ώστε να μην εμφανίζεται μήνυμα.</p>
